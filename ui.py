GOLD = "\033[93m"
CYAN = "\033[96m"
MAGENTA = "\033[95m"
GREEN = "\033[92m"
RED = "\033[91m"
DIM = "\033[2m"
BOLD = "\033[1m"
RESET = "\033[0m"

_tty = None


def _color_on():
    global _tty
    if _tty is None:
        if sys.stdout is None:
            _tty = False
        elif sys.stdout.isatty():
            os.system("")
            _tty = True
        else:
            _tty = False
    return _tty


def paint(text, code):
    return code + text + RESET if _color_on() else text


def banner(title, rows=()):
    if not _color_on():
        print(title)
        return
    print(paint(PIE_LOGO, GOLD))
    print(paint("  " + title, BOLD + MAGENTA))
    print()
    for label, value in rows:
        print("  " + paint(label.ljust(18), DIM) + paint(str(value), CYAN))
    print()


def ok(msg):
    print(paint("[+]", GREEN) + " " + msg)


def info(msg):
    print(paint("[*]", CYAN) + " " + msg)


def warn(msg):
    print(paint("[!]", RED) + " " + msg)


def res(agent, task_id, data, ok=True):
    tag = paint("[res]", GREEN if ok else RED)
    print(
        "%s %s %s %s" % (tag, paint(agent, CYAN), task_id, paint(str(data)[:300], DIM))
    )


def prompt(p="pie> "):
    return paint(p, BOLD + GOLD) if _color_on() else p
